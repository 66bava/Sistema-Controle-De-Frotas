import { exportar } from '../controllers/excelController.js';
import * as documentos from '../controllers/documentosController.js';
import { Router } from 'express';
import { autenticar, autorizar, protegerOrigem } from '../middlewares/authMiddleware.js';
import * as controller from '../controllers/ocorrenciasController.js';
const router = Router();
router.use(protegerOrigem, autenticar);
router.get('/exportar-excel', autorizar('admin'), exportar);
router.get('/filtros', controller.filtros);
router.get('/opcoes', autorizar('driver'), controller.opcoes);
router.get('/', controller.listar);
router.get('/:id', controller.buscar);
router.post('/', autorizar('driver'), controller.iniciar);
router.put('/:id/chegada', autorizar('driver'), controller.chegada);
router.post('/:id/assinatura', autorizar('driver'), controller.assinar);
router.get('/:id/assinatura', controller.assinatura);
router.get('/:id/pdf', documentos.pdf);
router.get('/:id/impressao', documentos.impressao);
export default router;
